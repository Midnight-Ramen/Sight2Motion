import { chromium, expect } from '@playwright/test';
import { mkdirSync } from 'node:fs';
import { openSetup } from './setup-ui.mjs';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900}});
await page.route('http://127.0.0.1:30061/**',r=>r.fulfill({body:'false'}));
try {
 await page.goto('http://127.0.0.1:5174/');
 await openSetup(page,'AI vision');
 const mode=page.getByRole('combobox',{name:'AI vision',exact:true});
 await expect(mode.locator('option')).toHaveCount(3);
 await expect(page.getByRole('button',{name:'Select target',exact:true})).toHaveCount(0);
 await expect(page.getByRole('checkbox',{name:'Show boxes'})).toBeVisible();
 await expect(page.getByRole('button',{name:'Load local model',exact:true})).toBeVisible();
 await mode.selectOption('teachable-machine');
 await expect(page.getByLabel('Model URL')).toBeVisible();
 await expect(page.getByRole('button',{name:'Select target',exact:true})).toHaveCount(0);
 await expect(page.locator('.selection-drawer')).toHaveCount(0);
 await expect(page.getByRole('checkbox',{name:'Show boxes'})).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Load local model',exact:true})).toHaveCount(0);
 await expect(page.locator('.preview-toolbar')).toContainText('class predictions');
 await expect(page.getByRole('button',{name:'Model classes',exact:true})).toBeVisible();
 await mode.selectOption('mobile-sam');
 await expect(page.getByLabel('Model URL')).toHaveCount(0);
 await expect(page.locator('.model-load')).toHaveCount(0);
 await expect(page.getByRole('checkbox',{name:'Show boxes'})).toHaveCount(0);
 await expect(page.locator('.selection-drawer > summary')).toHaveText('Selected target & Follow');
 await page.locator('.selection-drawer > summary').click();
 await expect(page.getByRole('button',{name:'Select target',exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:'Select target',exact:true})).toBeDisabled();
 await expect(page.locator('.preview-toolbar')).toHaveCount(0);
 await expect(page.locator('.target-advanced')).not.toHaveAttribute('open','');
 mkdirSync('test-results',{recursive:true});
 await page.screenshot({path:'test-results/vision-mobile-sam.png'});
 await mode.selectOption('yolo');
 await expect(page.locator('.selection-drawer')).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Select target',exact:true})).toHaveCount(0);
 await expect(page.getByRole('checkbox',{name:'Show boxes'})).toBeVisible();
 await expect(page.getByRole('button',{name:'Load local model',exact:true})).toBeVisible();
 console.log('YOLO, TM and MobileSAM contextual controls/loading, mode switching and selector checks passed.');
} finally {await browser.close();}
