import {chromium,expect} from '@playwright/test';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const outputs=[];
await page.route('http://127.0.0.1:30061/**',route=>{if(route.request().url().includes('/out/'))outputs.push(route.request().url());return route.fulfill({body:'false'});});
await page.addInitScript(()=>{window.cameraStarts=0;navigator.mediaDevices.getUserMedia=async()=>{window.cameraStarts++;throw new Error('No camera in this test');};});
try {
 await page.goto('http://127.0.0.1:5174/');
 const choose=async name=>{
  const previous=await page.getByLabel('Project name',{exact:true}).inputValue();
  await page.getByRole('button',{name:'Templates',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:new RegExp('^'+name+' ')}).locator('strong').click();
  await expect(page.getByLabel('Project name',{exact:true})).toHaveValue(previous);
  await expect(page.getByRole('region',{name:name+' details'})).toBeVisible();
  await page.getByRole('button',{name:'Use starter',exact:true}).focus();
  await page.getByRole('button',{name:'Use starter',exact:true}).press('Space');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.locator('#rules')).toBeFocused();
 };
 await page.getByLabel('Project name',{exact:true}).fill('Classroom draft');
 await choose('Self-Driving Car');
 expect(await page.evaluate(()=>localStorage.getItem('vision-robot-studio.projects.v1'))).toContain('Classroom draft');
 await expect(page.getByLabel('Base driving behavior',{exact:true})).toHaveValue('Cruise Forward');
 await expect(page.getByRole('checkbox',{name:'Emergency braking',exact:true})).toBeChecked();
 await expect(page.getByRole('button',{name:'Play rules',exact:false})).toBeDisabled();
 await choose('Line-Following Vehicle');
 await expect(page.getByLabel('Base driving behavior',{exact:true})).toHaveValue('Line Follow');
 await expect(page.getByLabel('Base driving speed',{exact:true})).toHaveValue('20');
 await choose('AI Reaction');
 await expect(page.getByLabel('Base driving behavior',{exact:true})).toHaveValue('None');
 await expect(page.locator('.starter-guidance')).toContainText('AI Reaction');
 await page.getByRole('button',{name:'Templates',exact:true}).click();
 const dialog=page.getByRole('dialog');
 const sorting=dialog.getByRole('button',{name:/^AI Sorting Mechanism /});
 await sorting.focus(); await sorting.press('Enter');
 await expect(sorting).toHaveAttribute('aria-pressed','true');
 const reaction=dialog.getByRole('button',{name:/^AI Reaction /});
 await reaction.focus(); await reaction.press('Space');
 await expect(reaction).toHaveAttribute('aria-pressed','true');
 await expect(page.getByLabel('Project name',{exact:true})).toHaveValue('AI Reaction');
 await sorting.locator('svg').click();
 await expect(sorting).toHaveAttribute('aria-pressed','true');
 await expect(dialog.getByRole('button',{name:'Use starter',exact:true})).toBeDisabled();
 await page.getByLabel('AI Sorting Mechanism output port').selectOption('3');
 await dialog.getByRole('button',{name:'Use starter',exact:true}).click();
 await expect(page.locator('.starter-guidance')).toContainText('AI Sorting Mechanism');
 await choose('Follow a Target');
 await page.getByRole('button',{name:'AI vision',exact:true}).click();
 await expect(page.locator('select').filter({has:page.locator('option[value="mobile-sam"]')})).toHaveValue('mobile-sam');
 await expect.poll(()=>page.evaluate(()=>window.cameraStarts)).toBe(0);
 expect(outputs).toEqual([]);
 await page.screenshot({path:'test-results/classroom-starters.png'});
 console.log('Starter selection, explicit ports, base presets, defaults, MobileSAM mode, and paused readiness passed; hardware blocked.');
} finally {await browser.close();}
