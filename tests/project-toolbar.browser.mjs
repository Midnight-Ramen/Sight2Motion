import {chromium,expect} from '@playwright/test';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const outputs=[];
await page.route('http://127.0.0.1:30061/**',route=>{if(route.request().url().includes('/out/'))outputs.push(route.request().url());return route.fulfill({body:'false'});});
try {
 await page.goto('http://127.0.0.1:5174/');
 await expect(page.locator('.project-buttons button')).toHaveCount(4);
 await expect(page.getByLabel('Duplicate project',{exact:true})).toHaveCount(0);
 await expect(page.getByLabel('Import and export',{exact:true})).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Import JSON',exact:true})).toHaveCount(0);
 await expect(page.getByRole('button',{name:'Export JSON',exact:true})).toHaveCount(0);
 await page.getByLabel('Project name',{exact:true}).fill('Current class project');
 const rulesBefore=await page.locator('.rule-card').count();
 await page.getByRole('button',{name:'New project',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'Create a new project?'});
 await expect(dialog).toBeVisible();
 await expect(page.getByLabel('Project name',{exact:true}).first()).toHaveValue('Current class project');
 await dialog.getByLabel('Project name',{exact:true}).fill('Discarded draft');
 await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
 await expect(page.getByLabel('Project name',{exact:true})).toHaveValue('Current class project');
 await expect(page.locator('.rule-card')).toHaveCount(rulesBefore);
 await page.getByRole('button',{name:'New project',exact:true}).click();
 await dialog.getByLabel('Project name',{exact:true}).fill('Our new robot');
 await dialog.getByRole('button',{name:'Create project',exact:true}).click();
 await expect(dialog).toHaveCount(0);
 await expect(page.getByLabel('Project name',{exact:true})).toHaveValue('Our new robot');
 await expect(page.locator('.rule-card')).toHaveCount(0);
 await expect(page.locator('#rules')).toBeFocused();
 expect(await page.evaluate(()=>localStorage.getItem('vision-robot-studio.projects.v1'))).toContain('Current class project');
 await page.getByRole('button',{name:'Templates',exact:true}).click();
 await expect(page.getByRole('dialog',{name:'Start a Project'})).toBeVisible();
 await page.getByRole('button',{name:'Close project chooser',exact:true}).click();
 const downloadPromise=page.waitForEvent('download');
 await page.getByRole('button',{name:'Save project',exact:true}).click();
 const download=await downloadPromise;
 expect(download.suggestedFilename()).toMatch(/Our.new.robot.*json/i);
 const chunks=[];for await(const chunk of await download.createReadStream())chunks.push(chunk);
 const bytes=Buffer.concat(chunks);const saved=JSON.parse(bytes.toString());
 expect(saved.name).toBe('Our new robot');expect(saved.rules).toEqual([]);
 await page.getByLabel('Project name',{exact:true}).fill('Temporary edit');
 const chooserPromise=page.waitForEvent('filechooser');
 await page.getByRole('button',{name:'Open',exact:true}).click();
 await (await chooserPromise).setFiles({name:download.suggestedFilename(),mimeType:'application/json',buffer:bytes});
 await expect(page.getByLabel('Project name',{exact:true})).toHaveValue('Our new robot');
 expect(outputs).toEqual([]);
 for(const width of [1440,700,390]){await page.setViewportSize({width,height:900});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);}
 console.log('Four-button toolbar, New/Cancel/Create, Templates, preserved draft, Save/Open round trip, no hardware output, and responsive checks passed.');
} finally {await browser.close();}
